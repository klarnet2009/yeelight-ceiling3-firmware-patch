#!/usr/bin/env python3
"""Generate decomp compile headers and ARM linker symbol tables from decomp/."""

import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECOMP_DIR = os.path.join(ROOT, "decomp")
DECOMP_SYM_H = os.path.join(DECOMP_DIR, "include", "decomp_symbols.h")
LD_SYM_PATH = os.path.join(ROOT, "firmware", "ld", "ceiling3_symbols.ld")

STDLIB_SKIP = {
    "memset", "memcpy", "memmove", "memcmp", "strlen", "strnlen",
    "strcpy", "strncpy", "strcat", "strncat", "strcmp", "strncmp",
    "strchr", "strrchr", "strstr", "snprintf", "vsnprintf", "sprintf",
    "printf", "sscanf", "strtol", "strtoul", "atoi", "atol",
    "malloc", "calloc", "realloc", "free", "abs", "qsort",
}

TOKEN_RE = re.compile(
    r"(\*?)\b(PTR_[^\s(),;\[\]\"]+|DAT_[0-9a-f]+|UNK_[0-9a-f]+|[uibc]Ram[0-9a-f]+)\b(\s*\[)?"
)
FUNC_SIG_RE = re.compile(
    r"^// ---- (\S+) @ [0-9a-f]+ \(size \d+\) ----\s*\n\s*\n([A-Za-z_][A-Za-z0-9_* \t]+?)\s+([A-Za-z_][A-Za-z0-9_]*)\(",
    re.M,
)

SDK_ALIASES = {
    "FUN_100afc14": "miio_net_get_state",
}


def scan_decomp():
    tokens = {}
    func_rets = {}
    for dirpath, _, filenames in os.walk(DECOMP_DIR):
        for fn in sorted(filenames):
            if not fn.endswith(".c"):
                continue
            fp = os.path.join(dirpath, fn)
            with open(fp, encoding="utf-8", errors="replace") as f:
                txt = f.read()
            for m in TOKEN_RE.finditer(txt):
                deref, tok, brk = m.group(1), m.group(2), m.group(3)
                if not tok.isidentifier():
                    continue
                is_ptr = bool(deref == "*" or brk) or tok.startswith("PTR_")
                tokens[tok] = tokens.get(tok, False) or is_ptr
            for m in FUNC_SIG_RE.finditer(txt):
                hdr_name, ret_type, def_name = m.group(1), " ".join(m.group(2).split()), m.group(3)
                if def_name.isidentifier() and def_name not in STDLIB_SKIP:
                    func_rets.setdefault(def_name, ret_type)
                    if hdr_name != def_name and hdr_name.isidentifier() and hdr_name not in STDLIB_SKIP:
                        func_rets.setdefault(hdr_name, ret_type)
    return tokens, func_rets


def write_decomp_symbols_header(tokens: dict, func_rets: dict):
    lines = [
        "#pragma once",
        "/* Auto-generated by tools/prep_decomp_build.py. Do not edit manually. */",
        "#include <stdint.h>",
        "",
    ]
    for tok, is_ptr in sorted(tokens.items()):
        if is_ptr:
            lines.append(f"extern uint8_t {tok}[];")
        else:
            lines.append(f"extern uintptr_t {tok};")
    lines.append("")
    for name, ret in sorted(func_rets.items()):
        lines.append(f"{ret} {name}();")
    lines.append("")

    os.makedirs(os.path.dirname(DECOMP_SYM_H), exist_ok=True)
    with open(DECOMP_SYM_H, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def write_linker_symbols():
    csv_path = os.path.join(DECOMP_DIR, "functions.csv")
    with open(csv_path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    seen = set()
    lines = [
        "/* Auto-generated by tools/prep_decomp_build.py from decomp/functions.csv */",
        "/* Thumb bit (| 1) applied for Cortex-M4F BL/BLX calls into segment-0 Flash XIP. */",
        "",
    ]
    for r in rows:
        name = r["name"]
        va = int(r["entry"], 16)
        if not name.isidentifier() or name in seen:
            continue
        seen.add(name)
        thumb_va = va if va >= 0x20000000 else (va | 1)
        lines.append(f"PROVIDE({name} = 0x{thumb_va:08x});")
        if name in SDK_ALIASES and SDK_ALIASES[name] not in seen:
            alias = SDK_ALIASES[name]
            seen.add(alias)
            lines.append(f"PROVIDE({alias} = 0x{thumb_va:08x});")

    lines.append("")
    os.makedirs(os.path.dirname(LD_SYM_PATH), exist_ok=True)
    with open(LD_SYM_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    return len(seen)


def main():
    tokens, func_rets = scan_decomp()
    write_decomp_symbols_header(tokens, func_rets)
    ld_count = write_linker_symbols()
    print(
        f"prep_decomp_build: {len(tokens)} data/pool symbols, "
        f"{len(func_rets)} declarations -> {os.path.relpath(DECOMP_SYM_H, ROOT)}; "
        f"{ld_count} Thumb symbols -> {os.path.relpath(LD_SYM_PATH, ROOT)}"
    )


if __name__ == "__main__":
    main()
